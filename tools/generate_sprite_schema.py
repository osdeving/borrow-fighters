#!/usr/bin/env python3
"""Generate the sprite wire contract from the runtime's canonical Rust structs.

No compiler or extra Python packages needed. This deliberately accepts only the
plain structs and serde attributes used by this manifest; unsupported syntax
fails instead of silently producing an incomplete contract. Runtime validation
still owns relationships between fields (clip references, in-frame boxes, etc.).
"""

import argparse
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/engine/sprites/manifest.rs"
SCHEMA = ROOT / "schemas/sprite.schema.json"
TYPES = ROOT / "tools/sprite-studio/src/sprite.generated.ts"
PRIMITIVES = {
    "String": {"type": "string"},
    "bool": {"type": "boolean"},
    "i32": {"type": "integer", "minimum": -(2**31), "maximum": 2**31 - 1},
    "u32": {"type": "integer", "minimum": 0, "maximum": 2**32 - 1},
    "f32": {"type": "number"},
}


def type_schema(rust_type, names):
    if rust_type in PRIMITIVES:
        return dict(PRIMITIVES[rust_type])
    for generic in ("Option", "Vec"):
        if rust_type.startswith(generic + "<") and rust_type.endswith(">"):
            inner = type_schema(rust_type[len(generic) + 1 : -1], names)
            if generic == "Option":
                return {"anyOf": [inner, {"type": "null"}]}
            return {"type": "array", "items": inner}
    if rust_type in names:
        return {"$ref": f"#/$defs/{rust_type}"}
    raise ValueError(f"Unsupported Rust field type: {rust_type}")


def contract():
    source = SOURCE.read_text()
    struct_pattern = r"pub struct (\w+) \{([^{}]*)\}"
    structs = re.findall(struct_pattern, source)
    if "#[serde" in re.sub(struct_pattern, "", source):
        raise ValueError("Unsupported serde attribute outside plain struct fields")
    names = {name for name, _ in structs}
    if "SpriteManifest" not in names:
        raise ValueError("Missing canonical SpriteManifest struct")
    definitions = {}
    for name, body in structs:
        properties, required, attributes = {}, [], []
        for raw_line in body.splitlines():
            line = raw_line.strip()
            if not line or line.startswith("///"):
                continue
            if line.startswith("#[serde(") and line.endswith(")]"):
                for attribute in line[8:-2].split(","):
                    attribute = attribute.strip()
                    if attribute not in (
                        "default",
                        'skip_serializing_if = "Option::is_none"',
                        'skip_serializing_if = "Vec::is_empty"',
                    ):
                        raise ValueError(f"Unsupported serde attribute: {attribute}")
                    attributes.append(attribute)
                continue
            field = re.fullmatch(r"pub (?:r#)?(\w+): ([\w<>]+),", line)
            if not field:
                raise ValueError(f"Unsupported syntax in {name}: {line}")
            field_name, rust_type = field.groups()
            properties[field_name] = type_schema(rust_type, names)
            if not rust_type.startswith("Option<") and "default" not in attributes:
                required.append(field_name)
            attributes = []
        if attributes:
            raise ValueError(f"Unattached serde attribute in {name}")
        definitions[name] = {
            "type": "object",
            "properties": properties,
            "required": required,
        }
    schema_name = re.search(r'pub const SPRITE_SCHEMA: &str = "([^"]+)";', source)
    if not schema_name:
        raise ValueError("Missing SPRITE_SCHEMA constant")
    definitions["SpriteManifest"]["properties"]["schema"]["const"] = schema_name[1]
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": "Generated from src/engine/sprites/manifest.rs by tools/generate_sprite_schema.py; do not edit.",
        "title": schema_name[1],
        "$ref": "#/$defs/SpriteManifest",
        "$defs": definitions,
    }


def typescript_type(field):
    if "const" in field:
        return json.dumps(field["const"])
    if "$ref" in field:
        return field["$ref"].split("/")[-1]
    if "anyOf" in field:
        return " | ".join(typescript_type(item) for item in field["anyOf"])
    if field["type"] == "array":
        return f"Array<{typescript_type(field['items'])}>"
    return {"integer": "number", "number": "number", "string": "string",
            "boolean": "boolean", "null": "null"}[field["type"]]


def typescript(schema):
    lines = ["// Generated by tools/generate_sprite_schema.py; do not edit.",
             "// Canonical types: src/engine/sprites/manifest.rs.", ""]
    for name, definition in schema["$defs"].items():
        lines.append(f"export type {name} = {{")
        for name, field in definition["properties"].items():
            optional = "" if name in definition["required"] else "?"
            lines.append(f"  {name}{optional}: {typescript_type(field)};")
        lines.extend(["};", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on stale generated files")
    args = parser.parse_args()
    schema = contract()
    stale = []
    for path, contents in ((SCHEMA, json.dumps(schema, indent=2) + "\n"),
                           (TYPES, typescript(schema))):
        if args.check:
            if not path.exists() or path.read_text() != contents:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
    if stale:
        raise SystemExit("Stale sprite contract: " + ", ".join(stale)
                         + ". Run ./dev schema build.")
    print("Sprite schema and TypeScript types " + ("are current." if args.check else "generated."))


if __name__ == "__main__":
    main()
